bool LunarCalendar::fromSolar(const QDate& solar, LunarDate* lunar, QString* error) {
    if (!lunar || !validSolar(solar)) return fail(error, QStringLiteral("农历日期超出 1900-2100 支持范围"));
    int year = solar.year();
    if (solar < kEpoch.addDays([&] {
        int days = 0;
        for (int y = 1900; y < year; ++y) days += lunarYearDays(y);
        return days;
    }())) --year;
    int remaining = kEpoch.addDays([&] {
        int days = 0;
        for (int y = 1900; y < year; ++y) days += lunarYearDays(y);
        return days;
    }()).daysTo(solar);
    const Year& row = kYears[year - 1900];
    for (int month = 1; month <= 12; ++month) {
        const int regular = daysInMonth(year, month, false);
        if (remaining < regular) {
            *lunar = LunarDate{year, month, remaining + 1, false, remaining + 1 == regular};
            if (error) error->clear();
            return true;
        }
        remaining -= regular;
        if (row.leap == month) {
            const int leap = daysInMonth(year, month, true);
            if (remaining < leap) {
                *lunar = LunarDate{year, month, remaining + 1, true, remaining + 1 == leap};
                if (error) error->clear();
                return true;
            }
            remaining -= leap;
        }
    }
    return fail(error, QStringLiteral("无法计算农历月份"));
}

bool LunarCalendar::toSolar(const LunarDate& lunar, QDate* solar, QString* error) {
    if (!solar || !validLunarDate(lunar))
        return fail(error, QStringLiteral("农历日期无效或超出支持范围"));
    const int days = daysInMonth(lunar.year, lunar.month, lunar.leapMonth);
    int offset = 0;
    for (int y = 1900; y < lunar.year; ++y) offset += lunarYearDays(y);
    for (int month = 1; month < lunar.month; ++month) {
        offset += daysInMonth(lunar.year, month, false);
        if (kYears[lunar.year - 1900].leap == month)
            offset += daysInMonth(lunar.year, month, true);
    }
    offset += daysInMonth(lunar.year, lunar.month, false);
    if (lunar.leapMonth) offset += lunar.day - 1;
    else offset = offset - days + lunar.day - 1;
    const QDate result = kEpoch.addDays(offset);
    if (!validSolar(result)) return fail(error, QStringLiteral("换算日期超出支持范围"));
    *solar = result;
    if (error) error->clear();
    return true;
}

QDate LunarCalendar::nextMonthly(const QDate& current, const LunarDate& anchor,
                                 bool repeatLeapMonth, bool* found) {
    if (found) *found = false;
    LunarDate currentLunar;
    if (!validLunarDate(anchor) || !fromSolar(current, &currentLunar)) return QDate();

    int year = currentLunar.year;
    int month = currentLunar.month;
    bool leap = currentLunar.leapMonth;
    // 关闭闰月重复时，下一个正常月最多只隔一个闰月；保留有界检查以防年表损坏。
    for (int step = 0; step < 14; ++step) {
        if (!advanceLunarMonth(&year, &month, &leap)) return QDate();
        if (leap && !repeatLeapMonth) continue;
        const int count = daysInMonth(year, month, leap);
        if (count <= 0) return QDate();
        // 原锚点始终不变：原月末跟随目标月月末，原固定日在短月才临时夹取。
        const int day = anchor.lastDay ? count : qMin(anchor.day, count);
        const LunarDate candidate{year, month, day, leap, day == count};
        QDate solar;
        if (!toSolar(candidate, &solar)) return QDate();
        if (solar > current) {
            if (found) *found = true;
            return solar;
        }
    }
    return QDate();
}

QDate LunarCalendar::nextYearly(const QDate& current, const LunarDate& anchor,
                                bool repeatLeapMonth, bool* found) {
    if (found) *found = false;
    LunarDate currentLunar;
    if (!validLunarDate(anchor) || !fromSolar(current, &currentLunar)) return QDate();

    for (int year = currentLunar.year; validLunarYear(year); ++year) {
        const bool hasLeap = kYears[year - 1900].leap == anchor.month;
        const bool preferLeap = anchor.leapMonth && hasLeap;
        // 闰月锚点在非闰年回到正常月；有对应闰月时优先保持原闰月。
        // 开启重复后，正常月和对应闰月都产生候选，并按时间先后选择。
        const bool includeRegular = !preferLeap || repeatLeapMonth;
        const bool includeLeap = hasLeap && (anchor.leapMonth || repeatLeapMonth);
        for (int part = 0; part < 2; ++part) {
            const bool leap = part == 1;
            if ((!leap && !includeRegular) || (leap && !includeLeap)) continue;
            const int count = daysInMonth(year, anchor.month, leap);
            if (count <= 0) continue;
            const int day = anchor.lastDay ? count : qMin(anchor.day, count);
            const LunarDate candidate{year, anchor.month, day, leap, day == count};
            QDate solar;
            if (!toSolar(candidate, &solar)) continue;
            if (solar > current) {
                if (found) *found = true;
                return solar;
            }
        }
    }
    return QDate();
}

int LunarCalendar::minimumSolarYear() { return 1900; }
int LunarCalendar::maximumSolarYear() { return 2100; }

