const int kYearCount = int(sizeof(kYears) / sizeof(kYears[0]));
const QDate kEpoch(1900, 1, 31);

bool fail(QString* error, const QString& text) {
    if (error) *error = text;
    return false;
}

bool validSolar(const QDate& solar) {
    return solar.isValid() && solar >= kEpoch && solar <= QDate(2100, 12, 31);
}

bool validLunarYear(int year) {
    return year >= 1900 && year < 1900 + kYearCount;
}

int daysInMonth(int year, int month, bool leap) {
    if (!validLunarYear(year) || month < 1 || month > 12) return 0;
    const Year& row = kYears[year - 1900];
    if (leap) return row.leap == month ? row.months[row.leap] : 0;
    // 上游年表按正常月、紧随其后的闰月排列，不是把闰月放在年末。
    const int index = month - 1 + (row.leap && month > row.leap ? 1 : 0);
    return row.months[index];
}

int lunarYearDays(int year) {
    int result = 0;
    const Year& row = kYears[year - 1900];
    for (int i = 0; i < (row.leap ? 13 : 12); ++i) result += row.months[i];
    return result;
}

bool validLunarDate(const LunarDate& lunar) {
    const int days = daysInMonth(lunar.year, lunar.month, lunar.leapMonth);
    return days > 0 && lunar.day >= 1 && lunar.day <= days;
}

bool advanceLunarMonth(int* year, int* month, bool* leap) {
    if (!validLunarYear(*year) || *month < 1 || *month > 12) return false;
    if (*leap) {
        *leap = false;
        ++*month;
    } else if (kYears[*year - 1900].leap == *month) {
        *leap = true;
    } else {
        ++*month;
    }
    if (*month > 12) {
        *month = 1;
        ++*year;
    }
    return validLunarYear(*year);
}

